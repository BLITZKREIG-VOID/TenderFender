from typing import Any


# ---------------------------------------------------------------------------
# ID formatting helpers
# ---------------------------------------------------------------------------

def _vid(n: int) -> str:
    """Return vendor ID string, e.g. 'V-001'."""
    return f"V-{n:03d}"


def _tid(n: int) -> str:
    """Return tender ID string, e.g. 'T-001'."""
    return f"T-{n:03d}"


def _pid(n: int) -> str:
    """Return person ID string, e.g. 'P-001'."""
    return f"P-{n:03d}"


def _aid(n: int) -> str:
    """Return address ID string, e.g. 'A-001'."""
    return f"A-{n:03d}"


def _ctid(n: int) -> str:
    """Return contact ID string, e.g. 'CT-001'."""
    return f"CT-{n:03d}"


def _bid_id(n: int) -> str:
    """Return buyer ID string, e.g. 'B-001'."""
    return f"B-{n:03d}"


