def _vid(n: int) -> str:
    """Return vendor ID string, e.g. 'V-001'."""
    return f"V-{n:03d}"


def _tid(n: int) -> str:
    """Return tender ID string, e.g. 'T-001'."""
    return f"T-{n:03d}"


