def generate_directors(
    num_vendors: int,
    rng: random.Random,
) -> list[dict[str, Any]]:
    """
    Generate the directors table and a mapping vendor_num -> person_id.

    R-1 constraint: P-010 must exist and be shared by V-045, V-046, V-047.
    Non-ring directors: roughly one director per 2–3 vendors with overlap.

    Returns
    -------
    directors : list of {person_id, name}
    ring_director_id : person_id for P-010
    """
    name_pool: set[str] = set()

    # Pre-create P-010 (R-1 shared director) with a fixed name
    p010_name = "Rajesh Mehta"
    name_pool.add(p010_name)
    directors: list[dict[str, Any]] = [{"person_id": _pid(10), "name": p010_name}]

    # Generate additional directors for non-R-1 vendors
    # Aim for ~100 directors for 200 vendors (shared directors are realistic)
    extra_count = max(50, num_vendors // 2)
    used_pids = {10}
    pid = 1
    while len(directors) <= extra_count + 1:
        if pid in used_pids:
            pid += 1
            continue
        name = _person_name(rng, name_pool)
        directors.append({"person_id": _pid(pid), "name": name})
        used_pids.add(pid)
        pid += 1

    directors.sort(key=lambda d: d["person_id"])
    return directors


def generate_vendors(
    num_vendors: int,
    rng: random.Random,
    directors: list[dict[str, Any]],
) -> tuple[list[dict[str, Any]], list[dict[str, Any]]]:
    """
    Generate the vendors and vendor_directors tables.

    Fixed cohorts
    -------------
    V-045: R-1; must NOT qualify T-002 (Class-B, low turnover, low exp)
    V-046: R-1; must NOT qualify T-002 (Class-B, moderate turnover, low exp)
    V-047: R-1; MUST qualify T-002 (Class-A, turnover=150, exp=20)
    V-100..V-103: R-2; varied attributes, no T-002 constraint

    All three R-1 vendors share:
    - director P-010
    - address_id A-007

    Returns
    -------
    vendors : list of vendor dicts
    vendor_directors : list of {vendor_id, person_id} dicts
    """
    name_pool: set[str] = set()

    # Director IDs available for general assignment (exclude P-010 from pool)
    dir_ids = [d["person_id"] for d in directors if d["person_id"] != _pid(10)]

    def _pick_directors(vid_n: int, rng_: random.Random) -> list[str]:
        """Pick 1–3 directors for a vendor, non-R-1."""
        count = rng_.randint(1, 3)
        return rng_.sample(dir_ids, min(count, len(dir_ids)))

    vendors: list[dict[str, Any]] = []
    vendor_directors: list[dict[str, Any]] = []

    # --- R-1 vendors (fixed) ---

    # V-045: Class-B, turnover far below T-002 threshold, exp far below threshold
    v045: dict[str, Any] = {
        "vendor_id": _vid(45),
        "name": _vendor_name(rng, name_pool),
        "turnover_cr": 20.0,        # << 100; comfortably fails T-002
        "years_experience": 8,      # << 15; comfortably fails T-002
        "registration_class": "Class-B",
        "address_id": _aid(R1_SHARED_ADDRESS),
        "contact_id": _ctid(45),
    }
    vendors.append(v045)
    vendor_directors.append({"vendor_id": _vid(45), "person_id": _pid(R1_SHARED_DIRECTOR)})

    # V-046: Class-B, turnover fails, experience also fails
    v046: dict[str, Any] = {
        "vendor_id": _vid(46),
        "name": _vendor_name(rng, name_pool),
        "turnover_cr": 35.0,        # << 100; comfortably fails T-002
        "years_experience": 10,     # << 15; comfortably fails T-002
        "registration_class": "Class-B",
        "address_id": _aid(R1_SHARED_ADDRESS),
        "contact_id": _ctid(46),
    }
    vendors.append(v046)
    vendor_directors.append({"vendor_id": _vid(46), "person_id": _pid(R1_SHARED_DIRECTOR)})

    # V-047: THE sole T-002 qualifier (SOURCE_OF_TRUTH.md §7)
    v047: dict[str, Any] = {
        "vendor_id": _vid(47),
        "name": _vendor_name(rng, name_pool),
        "turnover_cr": V047_TURNOVER,
        "years_experience": V047_EXPERIENCE,
        "registration_class": T002_REG_CLASS,
        "address_id": _aid(R1_SHARED_ADDRESS),
        "contact_id": _ctid(47),
    }
    vendors.append(v047)
    vendor_directors.append({"vendor_id": _vid(47), "person_id": _pid(R1_SHARED_DIRECTOR)})

    # --- R-2 vendors (fixed IDs, varied non-colluding attributes) ---
    r2_attrs = [
        # class, turnover, exp — none must qualify T-002 (turnover < 100 or exp < 15)
        ("Class-C", 45.0, 12),
        ("Class-B", 60.0, 9),
        ("Class-A", 55.0, 18),   # Class-A, exp OK, but turnover fails T-002
        ("Class-C", 30.0, 11),
    ]
    for i, vn in enumerate(R2_VENDOR_IDS):
        cls, tv, exp = r2_attrs[i]
        v: dict[str, Any] = {
            "vendor_id": _vid(vn),
            "name": _vendor_name(rng, name_pool),
            "turnover_cr": tv,
            "years_experience": exp,
            "registration_class": cls,
            "address_id": _aid(vn),
            "contact_id": _ctid(vn),
        }
        vendors.append(v)
        pdirs = _pick_directors(vn, rng)
        for pd in pdirs:
            vendor_directors.append({"vendor_id": _vid(vn), "person_id": pd})

    # Track reserved vendor numbers
    reserved = set(R1_VENDOR_IDS) | set(R2_VENDOR_IDS)

    # --- General vendors ---
    # Split into two cohorts:
    #   T-003 cohort  (V-001..V-025): always qualify T-003; never qualify T-002.
    #   Non-cohort: forced to fail T-003 on exactly one criterion.
    # This keeps the total T-003 qualifier count in the target range of 20-30
    # (plus ~7 from R-1/R-2 reserved vendors that naturally qualify, for ~32 total).
    address_counter = 10   # start address pool from A-010 to keep A-007 clean
    contact_counter = 1
    _t003_cohort_classes = ["Class-A", "Class-B", "Class-C"]

    for vn in range(1, num_vendors + 1):
        if vn in reserved:
            continue

        # Deterministic address / contact (DATA-001 provisional)
        address_counter += 1
        contact_counter += 1
        aid = _aid(address_counter)
        ctid = _ctid(contact_counter)

        if vn in T003_COHORT_VENDOR_NUMS:
            # T-003 qualifying cohort: non-MSE, turnover [15-80] cr, experience [5-20] yrs.
            # Turnover cap of 80 cr ensures no accidental T-002 qualification (needs >= 100).
            cohort_idx = vn - 1          # V-001 -> 0, V-025 -> 24
            cls = _t003_cohort_classes[cohort_idx % len(_t003_cohort_classes)]
            turnover = round(rng.uniform(15.0, 80.0), 2)
            experience = rng.randint(5, 20)

        else:
            # Non-cohort: fail T-003 on exactly one criterion chosen randomly.
            #   fail_mode 0 -> MSE class  (T-003 excludes MSE)
            #   fail_mode 1 -> non-MSE, turnover 0.5-4.5 cr  (below T-003 threshold of 5)
            #   fail_mode 2 -> non-MSE, experience 1-2 yrs   (below T-003 threshold of 3)
            fail_mode = rng.randint(0, 2)
            if fail_mode == 0:
                cls = "MSE"
                turnover = round(rng.uniform(2.0, 200.0), 2)
                experience = rng.randint(3, 30)
            elif fail_mode == 1:
                cls = rng.choice(["Class-A", "Class-B", "Class-C"])
                turnover = round(rng.uniform(0.5, 4.5), 2)
                experience = rng.randint(3, 30)
            else:  # fail_mode == 2
                cls = rng.choice(["Class-A", "Class-B", "Class-C"])
                turnover = round(rng.uniform(5.0, 200.0), 2)
                experience = rng.randint(1, 2)
                # experience 1-2 already fails T-002 (needs >= 15) — no extra guard needed.

        v = {
            "vendor_id": _vid(vn),
            "name": _vendor_name(rng, name_pool),
            "turnover_cr": turnover,
            "years_experience": experience,
            "registration_class": cls,
            "address_id": aid,
            "contact_id": ctid,
        }
        vendors.append(v)

        pdirs = _pick_directors(vn, rng)
        for pd in pdirs:
            vendor_directors.append({"vendor_id": _vid(vn), "person_id": pd})

    # Sort by vendor_id for stable output
    vendors.sort(key=lambda x: x["vendor_id"])
    vendor_directors.sort(key=lambda x: (x["vendor_id"], x["person_id"]))

    return vendors, vendor_directors


