def _vendor_name(rng: random.Random, used: set[str]) -> str:
    """Generate a unique vendor name."""
    for _ in range(500):
        name = f"{rng.choice(_PREFIXES)} {rng.choice(_SUFFIXES)}"
        if name not in used:
            used.add(name)
            return name
    # Fallback: append numeric suffix
    n = len(used) + 1
    name = f"Vendor Corp {n}"
    used.add(name)
    return name


