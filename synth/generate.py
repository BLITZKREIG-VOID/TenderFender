"""
TenderFender – Synthetic Data Generator (P2)
============================================
Responsible for generating all six CSV/JSON output files:
  data/vendors.csv
  data/directors.csv
  data/vendor_directors.csv
  data/tenders.csv
  data/bids.csv
  data/labels.json

Strategy
--------
* Fixed cohorts are built first for reserved vendor IDs (R-1, R-2).
* All remaining vendors are generated with seeded random variation.
* Every random.Random instance is explicitly seeded; global random state
  is never mutated.
* Planted scenarios (R-1 shared director/address, R-2 bid rotation,
  R-3 cover bids) are inserted deterministically.

DATA-001 (provisional): address_id and contact_id are opaque deterministic
identifiers generated by this module.  No additional entity CSV files are
created.  Pending P3 confirmation.

Do NOT import from graph/, rules/, fusion/, decision/, api/ or ui/.
"""

from __future__ import annotations

import random
