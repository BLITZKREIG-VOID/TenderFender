def qualifies_t002(vendor: dict[str, Any]) -> bool:
    """Return True if a vendor dict meets T-002 eligibility criteria."""
    return (
        vendor["registration_class"] == T002_REG_CLASS
        and vendor["turnover_cr"] >= T002_MIN_TURNOVER
        and vendor["years_experience"] >= T002_MIN_EXPERIENCE
    )


def qualifies_t003(vendor: dict[str, Any]) -> bool:
    """Return True if a vendor dict meets T-003 eligibility criteria."""
    return (
        vendor["registration_class"] in T003_REG_CLASSES
        and vendor["turnover_cr"] >= T003_MIN_TURNOVER
        and vendor["years_experience"] >= T003_MIN_EXPERIENCE
    )


