def generate_all(
    num_vendors: int = 200,
    num_tenders: int = 300,
    seed: int = 42,
) -> dict[str, Any]:
    """
    Generate all six synthetic datasets.

    Parameters
    ----------
    num_vendors : int, default 200
        Total number of vendors to generate.
    num_tenders : int, default 300
        Total number of tenders to generate.
    seed : int, default 42
        Random seed for full reproducibility.

    Returns
    -------
    dict with keys: vendors, directors, vendor_directors, tenders, bids, labels,
                    _cover_metadata (private; not written to CSV files).
    Each CSV-backed value is a list-of-dicts; labels and _cover_metadata are dicts.
    _cover_metadata: {tender_id: [cover_vid, ...]} for R-3 tenders only.
    """
    rng = random.Random(seed)

    directors = generate_directors(num_vendors, rng)
    vendors, vendor_directors = generate_vendors(num_vendors, rng, directors)
    tenders = generate_tenders(num_tenders, rng)
    bids, cover_metadata = generate_bids(vendors, tenders, rng)
    labels = generate_labels(tenders, bids)

    return {
        "vendors": vendors,
        "directors": directors,
        "vendor_directors": vendor_directors,
        "tenders": tenders,
        "bids": bids,
        "labels": labels,
        "_cover_metadata": cover_metadata,   # private: not written to any file
    }
