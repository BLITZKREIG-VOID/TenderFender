def _clamp_cover_amount(winner_amount: float, raw_cover: float) -> float:
    """
    Round a cover-bid amount to 2 dp and guarantee the resulting ratio to
    winner_amount is exactly in [1.01, 1.03] (both inclusive).

    Precision policy
    ----------------
    bid_amount_cr is stored with 2 decimal places.  Dividing two 2-dp values can
    produce a ratio that drifts slightly outside the intended cover-mult window of
    [1.01, 1.03] (observed range without clamping: ~[1.0096, 1.0303]).  We correct
    this by computing the 2-dp lower and upper boundary amounts, nudging each by
    the smallest representable unit (0.01) when necessary, then clamping the
    rounded cover amount between them.  The nudge is applied in fewer than 0.5% of
    cases and shifts the amount by at most one cent.
    """
    amount = round(raw_cover, 2)

    # Compute inclusive 2-dp boundary amounts.
    lo = round(winner_amount * 1.01, 2)
    hi = round(winner_amount * 1.03, 2)

    # Nudge boundaries inward if 2-dp rounding itself violated the ratio bound.
    if winner_amount > 0 and lo / winner_amount < 1.01:
        lo = round(lo + 0.01, 2)
    if winner_amount > 0 and hi / winner_amount > 1.03:
        hi = round(hi - 0.01, 2)

    return max(lo, min(hi, amount))


def generate_bids(
    vendors: list[dict[str, Any]],
    tenders: list[dict[str, Any]],
    rng: random.Random,
) -> tuple[list[dict[str, Any]], dict[str, list[str]]]:
    """
    Generate the bids table.

    Returns
    -------
    (bids, cover_metadata)
    bids          : list-of-dicts matching the SOURCE_OF_TRUTH §7 schema.
    cover_metadata: {tender_id: [cover_vid, ...]}  — private, not written to CSV.
                    Enables tests to identify planted cover bids by vendor ID
                    rather than by ratio window (non-tautological assertions).

    Strategy
    --------
    1. R-2 tenders T-004..T-015 rotate wins among V-100..V-103. Each R-2
       vendor bids on every rotation tender.
    2. R-3 tenders T-016..T-025 have a random winner and noise bidders, plus
       2–3 planted cover bids 1–3% above the winner. Cover bidders are never
       R-1 or R-2 members.
    3. Demo and remaining tenders receive ordinary noise bids only. T-003's
       bidder pool excludes R-1 and R-2 so it remains a clean control.

    Schema (SOURCE_OF_TRUTH.md §7):
      tender_id, vendor_id, bid_amount_cr, bid_ratio, rank, won, submitted_at
    """
    all_vendor_ids = [v["vendor_id"] for v in vendors]
    # General pool: excludes R-2 members (reserved for R-2 rotation)
    r2_vids = [_vid(n) for n in R2_VENDOR_IDS]
    general_vids = [vid for vid in all_vendor_ids if vid not in r2_vids]

    tender_list = list(tenders)   # already sorted by tender_id

    r2_tender_ids = {
        _tid(n) for n in range(R2_ROTATION_TENDER_START, R2_ROTATION_TENDER_END + 1)
    }
    r2_tenders = [t["tender_id"] for t in tender_list if t["tender_id"] in r2_tender_ids]
    r3_overlay_set = {_tid(n) for n in range(R3_TENDER_START, R3_TENDER_END + 1)}

    # Cover bidder pool: excludes R-1 and R-2 (separate from rotation winners)
    r1_vids = [_vid(n) for n in R1_VENDOR_IDS]
    reserved_vids = set(r1_vids + r2_vids)
    cover_bidder_pool = [vid for vid in general_vids if vid not in reserved_vids]
    demo_tender_ids = {_tid(1), _tid(2), _tid(3)}

    bids: list[dict[str, Any]] = []
    base_ts = datetime.datetime(2024, 1, 15, 9, 0, 0)
    # cover_metadata: {tender_id -> [cover_vid, ...]}  (private; not written to CSV)
    cover_metadata: dict[str, list[str]] = {}

    # --- R-2 rotation tenders (T-004..T-015) ---
    for i, tid in enumerate(r2_tenders):
        tender_obj = next(t for t in tender_list if t["tender_id"] == tid)
        estimated = tender_obj["estimated_value_cr"]
        winner_r2_vid = r2_vids[i % len(R2_VENDOR_IDS)]

        # R-2 winner bid: 80–95 % of estimate
        winner_amount = round(estimated * rng.uniform(0.80, 0.95), 2)

        # Build bid list: all 4 R-2 vendors bid; only the designated winner wins
        r2_bid_amounts: list[tuple[str, float]] = []
        for rv in r2_vids:
            if rv == winner_r2_vid:
                r2_bid_amounts.append((rv, winner_amount))
            else:
                # Losing R-2 member bids 2–15 % above winner
                lose_mult = rng.uniform(1.02, 1.15)
                r2_bid_amounts.append((rv, round(winner_amount * lose_mult, 2)))

        # Noise bidders from general pool (not R-1, not R-2)
        noise_count = rng.randint(2, 5)
        noise_vids = rng.sample(general_vids, min(noise_count, len(general_vids)))
        for nv in noise_vids:
            noise_amt = round(estimated * rng.uniform(0.85, 1.10), 2)
            r2_bid_amounts.append((nv, noise_amt))

        # Sort by amount to assign ranks
        r2_bid_amounts.sort(key=lambda x: x[1])

        submitted_at = base_ts + datetime.timedelta(days=i)

        for rank, (vid, amount) in enumerate(r2_bid_amounts, start=1):
            bid_ratio = round(amount / estimated, 4)
            won = 1 if vid == winner_r2_vid else 0
            bids.append({
                "tender_id": tid,
                "vendor_id": vid,
                "bid_amount_cr": amount,
                "bid_ratio": bid_ratio,
                "rank": rank,
                "won": won,
                "submitted_at": submitted_at.isoformat(),
            })

    # --- Demo and remaining tenders ---
    remaining_tids = [
        t["tender_id"] for t in tender_list
        if t["tender_id"] not in r2_tender_ids
    ]

    for k, tid in enumerate(remaining_tids):
        tender_obj = next(t for t in tender_list if t["tender_id"] == tid)
        estimated = tender_obj["estimated_value_cr"]

        tender_pool = general_vids
        if tid == _tid(3):
            # Keep the clean-control tender away from every flagged ownership
            # and rotation member while leaving T-001/T-002 otherwise normal.
            tender_pool = [vid for vid in general_vids if vid not in r1_vids]
        winner_vid = rng.choice(tender_pool)
        winner_amount = round(estimated * rng.uniform(0.75, 0.98), 2)

        bid_amounts: list[tuple[str, float]] = [(winner_vid, winner_amount)]

        extra_count = rng.randint(2, 8)
        extra_vids = rng.sample(
            [v for v in tender_pool if v != winner_vid],
            min(extra_count, len(tender_pool) - 1),
        )
        for ev in extra_vids:
            amt = round(estimated * rng.uniform(0.80, 1.25), 2)
            bid_amounts.append((ev, amt))

        if tid in r3_overlay_set:
            cover_count = rng.randint(R3_COVER_BIDDERS_MIN, R3_COVER_BIDDERS_MAX)
            already_bidding = {vendor_id for vendor_id, _ in bid_amounts}
            demo_bidders = {
                bid["vendor_id"] for bid in bids if bid["tender_id"] in demo_tender_ids
            }
            available_covers = [
                vid for vid in cover_bidder_pool
                if vid not in already_bidding and vid not in demo_bidders
            ]
            if len(available_covers) < cover_count:
                raise ValueError(
                    f"R-3 tender {tid} needs {cover_count} distinct cover bidders, "
                    f"only {len(available_covers)} are available"
                )
            cover_vids = rng.sample(available_covers, cover_count)
            cover_metadata[tid] = list(cover_vids)
            for cover_vid in cover_vids:
                multiplier = rng.uniform(R3_COVER_ABOVE_MIN, R3_COVER_ABOVE_MAX)
                amount = _clamp_cover_amount(winner_amount, winner_amount * (1.0 + multiplier))
                bid_amounts.append((cover_vid, amount))

        bid_amounts.sort(key=lambda x: x[1])

        submitted_at = base_ts + datetime.timedelta(
            days=R2_ROTATION_TENDER_COUNT + k
        )

        for rank, (vid, amount) in enumerate(bid_amounts, start=1):
            bid_ratio = round(amount / estimated, 4)
            won = 1 if vid == winner_vid else 0
            bids.append({
                "tender_id": tid,
                "vendor_id": vid,
                "bid_amount_cr": amount,
                "bid_ratio": bid_ratio,
                "rank": rank,
                "won": won,
                "submitted_at": submitted_at.isoformat(),
            })

    bids.sort(key=lambda x: (x["tender_id"], x["rank"]))
    return bids, cover_metadata


def generate_labels(
    tenders: list[dict[str, Any]],
    bids: list[dict[str, Any]],
    cover_metadata: dict[str, list[str]],
) -> dict[str, Any]:
    """
    Build labels.json.

    Schema (SOURCE_OF_TRUTH.md §7):
      {
        "rings": [{ring_id, vendor_ids, type}],
        "vendor_labels": {"V-xxx": 0|1},
        "planted_type": {"V-xxx": "shell_ring|rotation|cover|none"}
      }

    WARNING: labels must NEVER be used as model features.
    """
    r1_vids = [_vid(n) for n in R1_VENDOR_IDS]
    r2_vids = [_vid(n) for n in R2_VENDOR_IDS]
    # This evaluation-only membership comes from the generator's exact record
    # of which bids were planted, not from unrelated losing bids.
    flagged_r3 = {
        vendor_id
        for vendor_ids in cover_metadata.values()
        for vendor_id in vendor_ids
    }

    rings = [
        {
            "ring_id": "R-1",
            "vendor_ids": r1_vids,
            "type": "shell_ring",
        },
        {
            "ring_id": "R-2",
            "vendor_ids": r2_vids,
            "type": "rotation",
        },
    ]
    # Only include R-3 when cover bids were actually planted.
    if flagged_r3:
        rings.append({
            "ring_id": "R-3",
            "vendor_ids": sorted(flagged_r3),
            "type": "cover",
        })

    # Build per-vendor label and planted_type
    all_flagged = set(r1_vids) | set(r2_vids) | flagged_r3
    vendor_labels: dict[str, int] = {}
    planted_type: dict[str, str] = {}

    # Collect all vendor IDs from tenders data
    # (We don't have direct vendor list here, so infer from bids)
    all_bid_vids: set[str] = {b["vendor_id"] for b in bids}

    for vid in all_bid_vids:
        vendor_labels[vid] = 1 if vid in all_flagged else 0
        if vid in set(r1_vids):
            planted_type[vid] = "shell_ring"
        elif vid in set(r2_vids):
            planted_type[vid] = "rotation"
        elif vid in flagged_r3:
            planted_type[vid] = "cover"
        else:
            planted_type[vid] = "none"

    return {
        "rings": rings,
        "vendor_labels": dict(sorted(vendor_labels.items())),
        "planted_type": dict(sorted(planted_type.items())),
    }


